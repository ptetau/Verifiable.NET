using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace Verifiable.Generators;

/// <summary>
/// Requirement R10: effects for the outer shell. A partial interface marked <c>[Effects]</c> lists the
/// effects as <c>void</c> methods. The generator emits a closed union of effect values — an abstract
/// record with one sealed record per method — that pure code returns instead of performing I/O, and a
/// <c>Handle</c> / <c>HandleAll</c> dispatcher. The shell implements the interface, so every effect must
/// have a handler or the build fails (CS0535); the union's constructor is private, so no other case exists.
/// </summary>
[Generator(LanguageNames.CSharp)]
public sealed class EffectsGenerator : IIncrementalGenerator
{
    /// <inheritdoc />
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var declarations = context.SyntaxProvider.ForAttributeWithMetadataName(
            "Verifiable.Contracts.EffectsAttribute",
            static (node, _) => node is InterfaceDeclarationSyntax,
            static (ctx, _) => (Symbol: (INamedTypeSymbol)ctx.TargetSymbol, Syntax: (InterfaceDeclarationSyntax)ctx.TargetNode));
        context.RegisterSourceOutput(declarations, static (spc, d) => Emit(spc, d.Symbol, d.Syntax));
    }

    /// <summary><c>IBookingEffects</c> → <c>BookingEffect</c>.</summary>
    internal static string UnionName(string interfaceName)
    {
        var name = interfaceName.Length > 1 && interfaceName[0] == 'I' && char.IsUpper(interfaceName[1]) ? interfaceName.Substring(1) : interfaceName;
        if (name.EndsWith("Effects", StringComparison.Ordinal)) name = name.Substring(0, name.Length - 1);
        return name == interfaceName ? name + "Effect" : name;
    }

    private static string Pascal(string name) => name.Length == 0 ? name : char.ToUpperInvariant(name[0]) + name.Substring(1);

    private static void Emit(SourceProductionContext spc, INamedTypeSymbol iface, InterfaceDeclarationSyntax syntax)
    {
        var loc = syntax.Identifier.GetLocation();
        void Fail(string message) => spc.ReportDiagnostic(Diagnostic.Create(GeneratorDescriptors.InvalidEffects, loc, message));

        if (!syntax.Modifiers.Any(m => m.IsKind(SyntaxKind.PartialKeyword))) { Fail($"Effects interface `{iface.Name}` must be partial."); return; }
        if (iface.ContainingType is not null) { Fail($"Effects interface `{iface.Name}` must not be nested."); return; }

        var methods = iface.GetMembers().OfType<IMethodSymbol>().Where(m => m.MethodKind == MethodKind.Ordinary).ToList();
        if (methods.Count == 0) { Fail($"Effects interface `{iface.Name}` declares no effects."); return; }
        var ok = true;
        foreach (var m in methods)
        {
            if (!m.ReturnsVoid) { Fail($"Effect `{iface.Name}.{m.Name}` must return void: the shell performs it, the domain does not wait for an answer."); ok = false; }
            if (m.IsGenericMethod) { Fail($"Effect `{iface.Name}.{m.Name}` must not be generic."); ok = false; }
            if (m.Parameters.Any(p => p.RefKind != RefKind.None)) { Fail($"Effect `{iface.Name}.{m.Name}` must not have ref or out parameters."); ok = false; }
        }
        var dup = methods.GroupBy(m => m.Name).FirstOrDefault(g => g.Count() > 1);
        if (dup is not null) { Fail($"Effect `{iface.Name}.{dup.Key}` is declared more than once; give each effect its own name."); ok = false; }
        if (!ok) return;

        var union = UnionName(iface.Name);
        var ns = iface.ContainingNamespace.IsGlobalNamespace ? null : iface.ContainingNamespace.ToDisplayString();
        var access = iface.DeclaredAccessibility == Accessibility.Public ? "public" : "internal";
        string T(ITypeSymbol t) => t.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);

        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("#nullable enable");
        if (ns is not null) sb.AppendLine($"namespace {ns};");
        sb.AppendLine();
        sb.AppendLine($"/// <summary>The effects of <see cref=\"{iface.Name}\"/> as values: pure code returns them, the shell performs them.</summary>");
        sb.AppendLine($"{access} abstract record {union}");
        sb.AppendLine("{");
        sb.AppendLine($"    // Closed: only the cases below can derive from {union}.");
        sb.AppendLine($"    private {union}() {{ }}");
        foreach (var m in methods)
        {
            var fields = string.Join(", ", m.Parameters.Select(p => $"{T(p.Type)} {Pascal(p.Name)}"));
            sb.AppendLine();
            sb.AppendLine($"    /// <summary>Asks the shell to perform <see cref=\"{iface.Name}.{m.Name}\"/>.</summary>");
            sb.AppendLine($"    public sealed record {m.Name}({fields}) : {union};");
        }
        sb.AppendLine("}");
        sb.AppendLine();
        // Factories for verified code: the prover does not lower constructors of records that derive from a
        // record, so pure code calls these instead of `new`. They are trusted constructors with no logic.
        sb.AppendLine($"/// <summary>Creates <see cref=\"{union}\"/> values in verified code.</summary>");
        sb.AppendLine($"{access} static class {union}s");
        sb.AppendLine("{");
        foreach (var m in methods)
        {
            var ps = string.Join(", ", m.Parameters.Select(p => $"{T(p.Type)} {p.Name}"));
            var args = string.Join(", ", m.Parameters.Select(p => p.Name));
            sb.AppendLine($"    /// <summary>Asks the shell to perform <see cref=\"{iface.Name}.{m.Name}\"/>.</summary>");
            sb.AppendLine("    [global::Verifiable.Contracts.PureAxiom]");
            sb.AppendLine($"    public static {union} {m.Name}({ps}) => new {union}.{m.Name}({args});");
        }
        sb.AppendLine("}");
        sb.AppendLine();
        sb.AppendLine($"/// <summary>Runs <see cref=\"{union}\"/> values against a shell that implements <see cref=\"{iface.Name}\"/>.</summary>");
        sb.AppendLine($"{access} static class {union}Dispatch");
        sb.AppendLine("{");
        sb.AppendLine($"    /// <summary>Performs one effect.</summary>");
        sb.AppendLine($"    public static void Handle(this {iface.Name} shell, {union} effect)");
        sb.AppendLine("    {");
        sb.AppendLine("        switch (effect)");
        sb.AppendLine("        {");
        foreach (var m in methods)
        {
            var args = string.Join(", ", m.Parameters.Select(p => $"e.{Pascal(p.Name)}"));
            sb.AppendLine($"            case {union}.{m.Name} e: shell.{m.Name}({args}); return;");
        }
        sb.AppendLine($"            default: throw new global::System.ArgumentOutOfRangeException(nameof(effect), effect, \"Unknown {union}.\");");
        sb.AppendLine("        }");
        sb.AppendLine("    }");
        sb.AppendLine();
        sb.AppendLine($"    /// <summary>Performs effects in order.</summary>");
        sb.AppendLine($"    public static void HandleAll(this {iface.Name} shell, global::System.Collections.Generic.IEnumerable<{union}> effects)");
        sb.AppendLine("    {");
        sb.AppendLine("        foreach (var effect in effects) shell.Handle(effect);");
        sb.AppendLine("    }");
        sb.AppendLine("}");
        spc.AddSource($"{iface.Name}.Effects.g.cs", sb.ToString());
    }
}
