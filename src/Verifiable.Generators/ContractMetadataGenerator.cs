using System;
using System.Collections.Generic;
using System.Collections.Immutable;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace Verifiable.Generators;

/// <summary>
/// Exports canonical contract metadata (<c>[assembly: VerifiableContractMetadata(...)]</c>) for externally
/// accessible <c>[Verifiable]</c>, <c>[Ghost]</c>, <c>[Invariant]</c>, and <c>[TypeAlias&lt;T&gt;]</c> members
/// so referencing compilations can verify helper predicates, specifications, and invariants across assembly boundaries.
/// </summary>
[Generator(LanguageNames.CSharp)]
public sealed class ContractMetadataGenerator : IIncrementalGenerator
{
    private sealed record ExportedEntry(
        string MemberId,
        string Kind,
        string Expression,
        string? Description,
        int Order);

    /// <inheritdoc />
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var hasMetadataAttr = context.CompilationProvider.Select(static (comp, _) =>
            comp.GetTypeByMetadataName(TypeRefHelper.ContractMetadataAttributeMetadataName) is not null);

        var memberEntries = context.SyntaxProvider.CreateSyntaxProvider(
            predicate: static (node, _) => node is MethodDeclarationSyntax or PropertyDeclarationSyntax,
            transform: static (ctx, _) => ExtractEntries(ctx))
            .Where(static list => !list.IsDefaultOrEmpty)
            .Collect();

        var combined = hasMetadataAttr.Combine(memberEntries);

        context.RegisterSourceOutput(combined, static (spc, pair) =>
        {
            var (canEmit, groups) = pair;
            if (!canEmit || groups.IsDefaultOrEmpty)
            {
                return;
            }

            var all = new List<ExportedEntry>();
            var seen = new HashSet<(string MemberId, string Kind, string Expression)>();
            foreach (var group in groups)
            {
                foreach (var entry in group)
                {
                    if (seen.Add((entry.MemberId, entry.Kind, entry.Expression)))
                    {
                        all.Add(entry);
                    }
                }
            }

            if (all.Count == 0)
            {
                return;
            }

            all.Sort(static (a, b) =>
            {
                var c = StringComparer.Ordinal.Compare(a.MemberId, b.MemberId);
                if (c != 0) return c;
                c = StringComparer.Ordinal.Compare(a.Kind, b.Kind);
                if (c != 0) return c;
                c = a.Order.CompareTo(b.Order);
                return c != 0 ? c : StringComparer.Ordinal.Compare(a.Expression, b.Expression);
            });

            var sb = new StringBuilder();
            sb.AppendLine("// <auto-generated />");
            sb.AppendLine("#nullable enable");
            foreach (var entry in all)
            {
                sb.Append("[assembly: global::Verifiable.Contracts.VerifiableContractMetadata(")
                    .Append(TypeRefHelper.EscapeStringLiteral(entry.MemberId))
                    .Append(", ")
                    .Append(TypeRefHelper.EscapeStringLiteral(entry.Kind))
                    .Append(", ")
                    .Append(TypeRefHelper.EscapeStringLiteral(entry.Expression));
                if (entry.Description is not null)
                {
                    sb.Append(", ").Append(TypeRefHelper.EscapeStringLiteral(entry.Description));
                }
                sb.AppendLine(")]");
            }

            spc.AddSource("Verifiable.ContractMetadata.g.cs", sb.ToString());
        });
    }

    private static ImmutableArray<ExportedEntry> ExtractEntries(GeneratorSyntaxContext context)
    {
        var model = context.SemanticModel;
        var assembly = model.Compilation.Assembly;
        var allowInternal = HasInternalsVisibleTo(assembly);

        if (context.Node is MethodDeclarationSyntax md)
        {
            if (model.GetDeclaredSymbol(md) is not IMethodSymbol method)
            {
                return ImmutableArray<ExportedEntry>.Empty;
            }

            return ExtractMethodEntries(model, md, method, allowInternal);
        }

        if (context.Node is PropertyDeclarationSyntax pd)
        {
            if (model.GetDeclaredSymbol(pd) is not IPropertySymbol prop)
            {
                return ImmutableArray<ExportedEntry>.Empty;
            }

            return ExtractPropertyEntries(model, pd, prop, allowInternal);
        }

        return ImmutableArray<ExportedEntry>.Empty;
    }

    private static ImmutableArray<ExportedEntry> ExtractMethodEntries(
        SemanticModel model,
        MethodDeclarationSyntax md,
        IMethodSymbol method,
        bool allowInternal)
    {
        if (method.IsGenericMethod ||
            method.ContainingType is null ||
            method.ContainingType.IsGenericType ||
            method.MethodKind != MethodKind.Ordinary ||
            method.ReturnsByRef ||
            method.ReturnsByRefReadonly ||
            method.Parameters.Any(p => p.RefKind != RefKind.None) ||
            !IsExternallyExportable(method, allowInternal) ||
            HasAttribute(method, TypeRefHelper.PureAxiomAttributeMetadataName) ||
            HasAttribute(method, TypeRefHelper.GeneratedRegexAttributeMetadataName))
        {
            return ImmutableArray<ExportedEntry>.Empty;
        }

        var memberId = method.GetDocumentationCommentId();
        if (string.IsNullOrEmpty(memberId))
        {
            return ImmutableArray<ExportedEntry>.Empty;
        }

        var builder = ImmutableArray.CreateBuilder<ExportedEntry>();
        var order = 0;

        // 1. [TypeAlias<T>] / [Refined<T>] IsValid(T value)
        if (method.IsStatic &&
            method.Name == "IsValid" &&
            method.ReturnType.SpecialType == SpecialType.System_Boolean &&
            method.Parameters.Length == 1 &&
            TypeRefHelper.TryGetConstrainedUnderlyingType(method.ContainingType, out var underlying, out var aliasDesc) &&
            underlying is not null &&
            SymbolEqualityComparer.Default.Equals(method.Parameters[0].Type, underlying))
        {
            if (TryGetSingleReturnExpression(md, model, allowLeadingSpecs: false, out var isValidExpr) &&
                isValidExpr is not null &&
                ContractExpressionCanonicalizer.TryCanonicalize(model, isValidExpr, allowInternal, out var canon))
            {
                builder.Add(new ExportedEntry(memberId!, "IsValid", canon, aliasDesc, order++));
            }
            return builder.ToImmutable();
        }

        // 2. [Invariant] parameterless bool instance method
        if (!method.IsStatic &&
            method.Parameters.Length == 0 &&
            method.ReturnType.SpecialType == SpecialType.System_Boolean &&
            TryGetInvariantDescription(method, out var invDesc))
        {
            if (TryGetSingleReturnExpression(md, model, allowLeadingSpecs: false, out var invExpr) &&
                invExpr is not null &&
                ContractExpressionCanonicalizer.TryCanonicalize(model, invExpr, allowInternal, out var canon))
            {
                builder.Add(new ExportedEntry(memberId!, "Invariant", canon, invDesc, order++));
            }
            return builder.ToImmutable();
        }

        var isVerifiable = IsInVerifiableScope(method);
        var isGhost = HasAttribute(method, TypeRefHelper.GhostAttributeMetadataName);
        if (!isVerifiable && !isGhost)
        {
            return ImmutableArray<ExportedEntry>.Empty;
        }

        // 3. Spec.Requires / Spec.Ensures contracts
        if (md.Body is { } body)
        {
            foreach (var stmt in body.Statements)
            {
                if (stmt is not ExpressionStatementSyntax exprStmt ||
                    exprStmt.Expression is not InvocationExpressionSyntax inv ||
                    model.GetSymbolInfo(inv).Symbol is not IMethodSymbol target ||
                    target.ContainingType?.ToDisplayString() != "Verifiable.Contracts.Spec")
                {
                    continue;
                }

                var args = inv.ArgumentList.Arguments;
                if (args.Count is < 1 or > 2)
                {
                    continue;
                }

                string? because = null;
                if (args.Count == 2)
                {
                    var constBecause = model.GetConstantValue(args[1].Expression);
                    if (constBecause.HasValue && constBecause.Value is string bStr)
                    {
                        because = bStr;
                    }
                }

                if (target.Name == "Requires")
                {
                    if (ContractExpressionCanonicalizer.TryCanonicalize(model, args[0].Expression, allowInternal, out var canonReq))
                    {
                        builder.Add(new ExportedEntry(memberId!, "Requires", canonReq, because, order++));
                    }
                }
                else if (target.Name == "Ensures" && !method.ReturnsVoid)
                {
                    ExpressionSyntax? ensExpr = null;
                    IParameterSymbol? lambdaParam = null;

                    if (args[0].Expression is SimpleLambdaExpressionSyntax simpleLambda &&
                        simpleLambda.ExpressionBody is not null)
                    {
                        ensExpr = simpleLambda.ExpressionBody;
                        lambdaParam = model.GetDeclaredSymbol(simpleLambda.Parameter);
                    }
                    else if (args[0].Expression is ParenthesizedLambdaExpressionSyntax parenLambda &&
                             parenLambda.ParameterList.Parameters.Count == 1 &&
                             parenLambda.ExpressionBody is not null)
                    {
                        ensExpr = parenLambda.ExpressionBody;
                        lambdaParam = model.GetDeclaredSymbol(parenLambda.ParameterList.Parameters[0]);
                    }
                    else if (args[0].Expression is not AnonymousFunctionExpressionSyntax)
                    {
                        ensExpr = args[0].Expression;
                    }

                    if (ensExpr is not null &&
                        ContractExpressionCanonicalizer.TryCanonicalize(model, ensExpr, allowInternal, out var canonEns, lambdaParam))
                    {
                        builder.Add(new ExportedEntry(memberId!, "Ensures", canonEns, because, order++));
                    }
                }
            }
        }

        // 4. Definitional / single-return body for pure helpers & [Ghost] methods
        if (!method.ReturnsVoid &&
            ((!method.IsVirtual && !method.IsOverride) || method.IsSealed || method.ContainingType.IsSealed) &&
            TryGetSingleReturnExpression(md, model, allowLeadingSpecs: true, out var bodyExpr) &&
            bodyExpr is not null &&
            ContractExpressionCanonicalizer.TryCanonicalize(model, bodyExpr, allowInternal, out var canonBody))
        {
            builder.Add(new ExportedEntry(memberId!, "Body", canonBody, null, order++));
        }

        return builder.ToImmutable();
    }

    private static ImmutableArray<ExportedEntry> ExtractPropertyEntries(
        SemanticModel model,
        PropertyDeclarationSyntax pd,
        IPropertySymbol prop,
        bool allowInternal)
    {
        if (prop.IsStatic ||
            prop.IsIndexer ||
            prop.ContainingType is null ||
            prop.ContainingType.IsGenericType ||
            !IsExternallyExportable(prop, allowInternal))
        {
            return ImmutableArray<ExportedEntry>.Empty;
        }

        var memberId = prop.GetDocumentationCommentId();
        if (string.IsNullOrEmpty(memberId))
        {
            return ImmutableArray<ExportedEntry>.Empty;
        }

        ExpressionSyntax? bodyExpr = null;
        if (pd.ExpressionBody is not null)
        {
            bodyExpr = pd.ExpressionBody.Expression;
        }
        else if (pd.AccessorList is not null)
        {
            var getter = pd.AccessorList.Accessors.FirstOrDefault(a => a.Keyword.IsKind(SyntaxKind.GetKeyword));
            if (getter?.ExpressionBody is not null)
            {
                bodyExpr = getter.ExpressionBody.Expression;
            }
            else if (getter?.Body is { Statements.Count: 1 } gBody &&
                     gBody.Statements[0] is ReturnStatementSyntax gRet)
            {
                bodyExpr = gRet.Expression;
            }
        }

        if (bodyExpr is null)
        {
            return ImmutableArray<ExportedEntry>.Empty;
        }

        // [Invariant] bool property
        if (prop.Type.SpecialType == SpecialType.System_Boolean &&
            TryGetInvariantDescription(prop, out var invDesc))
        {
            if (ContractExpressionCanonicalizer.TryCanonicalize(model, bodyExpr, allowInternal, out var canon))
            {
                return ImmutableArray.Create(new ExportedEntry(memberId!, "Invariant", canon, invDesc, 0));
            }
            return ImmutableArray<ExportedEntry>.Empty;
        }

        // Computed property on [Verifiable] type or marked [Ghost]
        if (IsInVerifiableScope(prop) || HasAttribute(prop, TypeRefHelper.GhostAttributeMetadataName))
        {
            if (ContractExpressionCanonicalizer.TryCanonicalize(model, bodyExpr, allowInternal, out var canon))
            {
                return ImmutableArray.Create(new ExportedEntry(memberId!, "Body", canon, null, 0));
            }
        }

        return ImmutableArray<ExportedEntry>.Empty;
    }

    private static bool TryGetSingleReturnExpression(
        MethodDeclarationSyntax md,
        SemanticModel model,
        bool allowLeadingSpecs,
        out ExpressionSyntax? expr)
    {
        if (md.ExpressionBody is not null)
        {
            expr = md.ExpressionBody.Expression;
            return true;
        }

        if (md.Body is { Statements.Count: > 0 } body &&
            body.Statements.Last() is ReturnStatementSyntax ret &&
            ret.Expression is not null)
        {
            if (body.Statements.Count == 1)
            {
                expr = ret.Expression;
                return true;
            }

            if (allowLeadingSpecs)
            {
                for (var i = 0; i < body.Statements.Count - 1; i++)
                {
                    if (body.Statements[i] is not ExpressionStatementSyntax exprStmt ||
                        exprStmt.Expression is not InvocationExpressionSyntax inv ||
                        model.GetSymbolInfo(inv).Symbol is not IMethodSymbol target ||
                        target.ContainingType?.ToDisplayString() != "Verifiable.Contracts.Spec" ||
                        target.Name is not ("Requires" or "Ensures"))
                    {
                        expr = null;
                        return false;
                    }
                }

                expr = ret.Expression;
                return true;
            }
        }

        expr = null;
        return false;
    }

    private static bool HasInternalsVisibleTo(IAssemblySymbol assembly) =>
        assembly.GetAttributes().Any(a =>
            a.AttributeClass?.ToDisplayString() == "System.Runtime.CompilerServices.InternalsVisibleToAttribute");

    private static bool IsExternallyExportable(ISymbol symbol, bool allowInternal)
    {
        if (!IsAccessibilityExportable(symbol.DeclaredAccessibility, allowInternal))
        {
            return false;
        }

        if (symbol is IPropertySymbol prop && prop.GetMethod is not null &&
            !IsAccessibilityExportable(prop.GetMethod.DeclaredAccessibility, allowInternal))
        {
            return false;
        }

        for (var cur = symbol.ContainingType; cur is not null; cur = cur.ContainingType)
        {
            if (!IsAccessibilityExportable(cur.DeclaredAccessibility, allowInternal))
            {
                return false;
            }
        }

        return true;
    }

    private static bool IsAccessibilityExportable(Accessibility accessibility, bool allowInternal) =>
        accessibility is Accessibility.Public or Accessibility.Protected or Accessibility.ProtectedOrInternal ||
        (allowInternal && accessibility is Accessibility.Internal or Accessibility.ProtectedAndInternal);

    private static bool HasAttribute(ISymbol symbol, string metadataFullName) =>
        symbol.GetAttributes().Any(a => a.AttributeClass?.ToDisplayString() == metadataFullName);

    private static bool TryGetInvariantDescription(ISymbol symbol, out string? description)
    {
        foreach (var attr in symbol.GetAttributes())
        {
            if (attr.AttributeClass?.ToDisplayString() == TypeRefHelper.InvariantAttributeMetadataName)
            {
                description = attr.ConstructorArguments.Length >= 1
                    ? attr.ConstructorArguments[0].Value as string
                    : null;
                return true;
            }
        }

        description = null;
        return false;
    }

    private static bool IsInVerifiableScope(ISymbol symbol)
    {
        for (var cur = symbol; cur is not null; cur = cur.ContainingSymbol)
        {
            if (cur is INamespaceSymbol or IModuleSymbol)
            {
                break;
            }

            if (HasAttribute(cur, TypeRefHelper.UnverifiableAttributeMetadataName))
            {
                return false;
            }

            if (HasAttribute(cur, TypeRefHelper.VerifiableAttributeMetadataName))
            {
                return true;
            }
        }

        return symbol.ContainingAssembly is { } asm &&
            HasAttribute(asm, TypeRefHelper.VerifiableAttributeMetadataName);
    }
}
